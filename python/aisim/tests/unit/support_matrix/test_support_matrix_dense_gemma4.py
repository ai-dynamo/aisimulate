"""The CLI support matrix must agree with the dense Gemma 4 classifier.

Before ``check_is_moe`` read the parsed expert configuration, every ``GEMMA4MIX``
checkpoint was treated as routed-MoE, so the sweeper enumerated ``moe_ep>1``
shapes and the dense guard rejected them. The generated matrix recorded that
rejection. Now that the classifier resolves the family from the metadata, a row
the generator still enumerates may not carry the dense diagnostic any more.

The matrix is cumulative: rows for backend versions the generator no longer
enumerates are historical records and are not regenerated by this check. The
op-level FPE matrix is built from one campaign shard set with a single source
identity, so it is regenerated by that campaign rather than per pull request.
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import pytest
from tools.support_matrix.support_matrix import SupportMatrix

from aisim_core.sdk.models import check_is_moe

pytestmark = pytest.mark.unit

DENSE_REJECTION = "dense Gemma 4 variants require moe_ep_size=1"
GEMMA4_ARCHITECTURE = "Gemma4ForConditionalGeneration"

MATRIX_DIR = Path(__file__).resolve().parents[3] / "src" / "aisim_core" / "systems" / "support_matrix"


def _matrix_rows():
    for path in sorted(MATRIX_DIR.glob("*.csv")):
        with path.open(newline="") as handle:
            for row in csv.DictReader(handle):
                yield path.name, row


def _current_combinations() -> set[tuple[str, str, str, str]]:
    return set(SupportMatrix().generate_combinations())


def _dense_gemma4_rows(rows):
    # Check the architecture first so unrelated models never reach the metadata
    # lookup, and so the coverage assertion cannot be satisfied by some other
    # dense family.
    return [
        (path, row)
        for path, row in rows
        if row["Architecture"] == GEMMA4_ARCHITECTURE and not check_is_moe(row["HuggingFaceID"])
    ]


def test_no_current_cli_matrix_row_records_the_dense_gemma4_rejection():
    current = _current_combinations()
    offenders = []
    for path, row in _dense_gemma4_rows(_matrix_rows()):
        if DENSE_REJECTION not in (row.get("ErrMsg") or ""):
            continue
        key = (row["HuggingFaceID"], row["System"], row["Backend"], row["Version"])
        if key not in current:
            continue
        offenders.append(f"{path} {row['Mode']}: {key}")
    assert not offenders, (
        "Regenerate the CLI support matrix for these combinations: the classifier no longer rejects dense "
        "Gemma 4 expert parallelism, so the row contradicts it.\n" + "\n".join(offenders)
    )


def test_the_current_cli_matrix_still_covers_a_dense_gemma4_checkpoint():
    # Guard against the check above passing because the checkpoint silently
    # dropped out of the matrix.
    current = _current_combinations()
    covered = [
        (path, row)
        for path, row in _dense_gemma4_rows(_matrix_rows())
        if (row["HuggingFaceID"], row["System"], row["Backend"], row["Version"]) in current
    ]
    assert covered, "no currently enumerated row covers a dense Gemma 4 checkpoint"
    stale = [f"{path} {row['Mode']}" for path, row in covered if DENSE_REJECTION in (row.get("ErrMsg") or "")]
    assert not stale, "dense Gemma 4 rows still record the pre-fix rejection: " + ", ".join(stale)


def test_dense_gemma4_coverage_check_ignores_other_dense_families(monkeypatch):
    # Removing every Gemma 4 row must fail the coverage assertion even though
    # the matrix still contains dense rows from other families.
    rows = list(_matrix_rows())
    without_gemma4 = [(path, row) for path, row in rows if row["Architecture"] != GEMMA4_ARCHITECTURE]
    assert any(not check_is_moe(row["HuggingFaceID"]) for _path, row in without_gemma4)
    monkeypatch.setattr(sys.modules[__name__], "_matrix_rows", lambda: iter(without_gemma4))
    with pytest.raises(AssertionError, match="no currently enumerated row covers a dense Gemma 4 checkpoint"):
        test_the_current_cli_matrix_still_covers_a_dense_gemma4_checkpoint()
